// Command mrcatz adalah CLI scaffolding MrCatz DataTable (pengganti
// `php artisan mrcatz:make` / `mrcatz:remove`, port dari CLI JS).
//
//	go run github.com/mrc4tz/mrcatz-go-datatables/cmd/mrcatz make Product [--path admin] [--model Product]
//	    [--table products] [--api internal] [--web apps/web/app/pages | --no-web] [--api-base /api] [--force]
//	go run github.com/mrc4tz/mrcatz-go-datatables/cmd/mrcatz remove Product [--path admin] [...opsi folder sama] [--force]
package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/mrc4tz/mrcatz-go-datatables/cmd/mrcatz/internal/scaffold"
)

const help = `MrCatz DataTable CLI

Usage:
  mrcatz make <Name> [options]     Generate table + Gin handlers (Go) + page (Nuxt)
  mrcatz remove <Name> [options]   Delete the files generated by "make"

Options:
  --path <dir>        Sub-folder, e.g. admin
  --model <name>      GORM model struct type (default: PascalCase name)
  --table <name>      Database table (default: snake_case plural)
  --api <dir>         Go packages folder (default: internal)
  --web <dir>         Nuxt pages folder (default: apps/web/app/pages)
  --no-web            Skip the Nuxt page
  --api-base <url>    API prefix used by the page (default: /api)
  --force             Overwrite (make) / skip confirmation (remove)
`

func main() {
	wd, err := os.Getwd()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Exit(run(os.Args[1:], wd, os.Stdin, os.Stdout, os.Stderr))
}

// parseArgs mem-parse flag dengan paket flag, tetapi mengizinkan argumen
// posisi di mana saja (mis. `make Product --path admin`).
func parseArgs(args []string, stderr io.Writer) (opts scaffold.Options, force bool, positional []string, err error) {
	fs := flag.NewFlagSet("mrcatz", flag.ContinueOnError)
	fs.SetOutput(stderr)
	fs.Usage = func() { fmt.Fprint(stderr, help) }
	fs.StringVar(&opts.Path, "path", "", "")
	fs.StringVar(&opts.Model, "model", "", "")
	fs.StringVar(&opts.Table, "table", "", "")
	fs.StringVar(&opts.APIDir, "api", "", "")
	fs.StringVar(&opts.WebDir, "web", "", "")
	fs.BoolVar(&opts.NoWeb, "no-web", false, "")
	fs.StringVar(&opts.APIBase, "api-base", "", "")
	fs.BoolVar(&force, "force", false, "")
	for {
		if err = fs.Parse(args); err != nil {
			return
		}
		args = fs.Args()
		if len(args) == 0 {
			return
		}
		positional = append(positional, args[0])
		args = args[1:]
	}
}

func run(args []string, cwd string, stdin io.Reader, stdout, stderr io.Writer) int {
	opts, force, pos, err := parseArgs(args, stderr)
	if errors.Is(err, flag.ErrHelp) {
		return 0
	}
	if err != nil {
		return 1
	}
	if len(pos) < 2 || (pos[0] != "make" && pos[0] != "remove") {
		fmt.Fprint(stdout, help)
		if len(pos) == 0 {
			return 0
		}
		return 1
	}
	if len(pos) > 2 {
		fmt.Fprintf(stderr, "Argumen berlebih: %s\n", strings.Join(pos[2:], " "))
		return 1
	}
	opts.Name = pos[1]
	names, err := scaffold.Resolve(opts)
	if err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	files, err := scaffold.Plan(opts)
	if err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	abs := func(f scaffold.File) string { return filepath.Join(cwd, filepath.FromSlash(f.Path)) }
	exists := func(f scaffold.File) bool { _, err := os.Stat(abs(f)); return err == nil }

	if pos[0] == "make" {
		var clash []string
		for _, f := range files {
			if exists(f) {
				clash = append(clash, "  "+f.Path)
			}
		}
		if len(clash) > 0 && !force {
			fmt.Fprintf(stderr, "Sudah ada (pakai --force untuk menimpa):\n%s\n", strings.Join(clash, "\n"))
			return 1
		}
		for _, f := range files {
			p := abs(f)
			if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
				fmt.Fprintln(stderr, err)
				return 1
			}
			if err := os.WriteFile(p, []byte(f.Content), 0o644); err != nil {
				fmt.Fprintln(stderr, err)
				return 1
			}
			fmt.Fprintf(stdout, "  ✓ %s\n", f.Path)
		}
		fmt.Fprintf(stdout, "\nSelesai. Daftarkan route di router Gin (import paket %s):\n\n", names.PackageDir)
		fmt.Fprintf(stdout, "  api := router.Group(%q)\n  if err := %s.Register(api, db); err != nil { ... }\n", names.APIBase, names.Package)
		return 0
	}

	var existing []scaffold.File
	for _, f := range files {
		if exists(f) {
			existing = append(existing, f)
		}
	}
	if len(existing) == 0 {
		fmt.Fprintln(stdout, "Tidak ada file untuk dihapus.")
		return 0
	}
	for _, f := range existing {
		fmt.Fprintf(stdout, "  %s\n", f.Path)
	}
	if !force {
		fmt.Fprintf(stdout, "Hapus %d file di atas? (y/N) ", len(existing))
		answer, _ := bufio.NewReader(stdin).ReadString('\n')
		if !yesRe.MatchString(strings.TrimSpace(answer)) {
			return 1
		}
	}
	for _, f := range existing {
		p := abs(f)
		if err := os.Remove(p); err != nil {
			fmt.Fprintln(stderr, err)
			return 1
		}
		// Bersihkan folder paket yang jadi kosong.
		dir := filepath.Dir(p)
		if entries, err := os.ReadDir(dir); err == nil && len(entries) == 0 {
			_ = os.Remove(dir)
		}
		fmt.Fprintf(stdout, "  ✗ %s\n", f.Path)
	}
	return 0
}

var yesRe = regexp.MustCompile(`(?i)^y(es)?$`)
